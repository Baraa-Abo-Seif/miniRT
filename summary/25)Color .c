//! **************************************************************************
//!                           Color Scale
//! **************************************************************************

/*
===============================================================================
CONCEPT
===============================================================================

Color scaling changes the intensity of a color.

Each RGB component is multiplied by the same scalar value.

-------------------------------------------------------------------------------
Formula
-------------------------------------------------------------------------------

Result = Color × k

Where

    Result.r = Color.r × k
    Result.g = Color.g × k
    Result.b = Color.b × k

-------------------------------------------------------------------------------
Usage
-------------------------------------------------------------------------------

This operation is mainly used to control light intensity.

Examples:

• Ambient Ratio
• Diffuse Intensity
• Future Lighting Calculations

-------------------------------------------------------------------------------
Example
-------------------------------------------------------------------------------

Color

    (1.0, 0.5, 0.2)

Scalar

    0.2

Result

    (0.2, 0.1, 0.04)

-------------------------------------------------------------------------------
Key Idea
-------------------------------------------------------------------------------

Color scaling does not change the hue.

It only changes the brightness of the color.

===============================================================================
*/
//! **************************************************************************
//!                          Color Multiply
//! **************************************************************************

/*
===============================================================================
CONCEPT
===============================================================================

Color multiplication simulates how light interacts with a surface.

Each RGB component is multiplied independently.

-------------------------------------------------------------------------------
Formula
-------------------------------------------------------------------------------

Result = A × B

Where

    Result.r = A.r × B.r
    Result.g = A.g × B.g
    Result.b = A.b × B.b

-------------------------------------------------------------------------------
Usage
-------------------------------------------------------------------------------

This operation models how much of each light component is reflected by the
object.

It is mainly used in lighting calculations, such as:

• Ambient Lighting
• Diffuse Lighting

-------------------------------------------------------------------------------
Example
-------------------------------------------------------------------------------

Object Color

    (1.0, 0.0, 0.0)

Light Color

    (1.0, 1.0, 1.0)

Result

    (1.0, 0.0, 0.0)

-------------------------------------------------------------------------------
Key Idea
-------------------------------------------------------------------------------

Color multiplication combines two colors by multiplying each RGB channel
independently.

It represents the physical interaction between light and surface color.

===============================================================================
*/


//! **************************************************************************
//!                             Color Addition
//! **************************************************************************

/*
===============================================================================
CONCEPT
===============================================================================

Color addition combines multiple lighting contributions into one final color.

Each RGB component is added independently.

-------------------------------------------------------------------------------
Formula
-------------------------------------------------------------------------------

Result = A + B

Where

    Result.r = A.r + B.r
    Result.g = A.g + B.g
    Result.b = A.b + B.b

-------------------------------------------------------------------------------
Usage
-------------------------------------------------------------------------------

This operation is used after each lighting component has been computed.

Examples:

    Final Color

        =

    Ambient

        +

    Diffuse

        +

    (Future Specular)

-------------------------------------------------------------------------------
Example
-------------------------------------------------------------------------------

Ambient

    (0.20, 0.00, 0.00)

Diffuse

    (0.50, 0.00, 0.00)

Result

    (0.70, 0.00, 0.00)

-------------------------------------------------------------------------------
Key Idea
-------------------------------------------------------------------------------

Color addition does not simulate light interaction.

It combines the results of different lighting calculations into the final
pixel color.

===============================================================================
*/

//! **************************************************************************
//!                        Color → Hex Conversion
//! **************************************************************************

/*
===============================================================================
CONCEPT
===============================================================================

MiniRT computes colors using floating-point RGB values:

    r, g, b ∈ [0.0, 1.0]

However, MLX expects a single 24-bit integer:

    0xRRGGBB

Therefore, every computed color must be converted before being drawn.

-------------------------------------------------------------------------------
STEP 1 — Clamp
-------------------------------------------------------------------------------

Ensure every channel remains inside

    [0.0 , 1.0]

This prevents invalid values after lighting calculations.

-------------------------------------------------------------------------------
STEP 2 — Convert to 8-bit
-------------------------------------------------------------------------------

Scale each channel

    value * 255

Examples

    0.0 →   0

    0.5 → 127

    1.0 → 255

-------------------------------------------------------------------------------
STEP 3 — Pack into RGB Integer
-------------------------------------------------------------------------------

Red occupies the highest byte

    red << 16

Green occupies the middle byte

    green << 8

Blue occupies the lowest byte

    blue

The final color is

    (red << 16) | (green << 8) | blue

-------------------------------------------------------------------------------
Pipeline
-------------------------------------------------------------------------------

Floating RGB

        ↓

Clamp

        ↓

Scale to 255

        ↓

Pack Bits

        ↓

0xRRGGBB

        ↓

MLX Pixel

===============================================================================
*/


